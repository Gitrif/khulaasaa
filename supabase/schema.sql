-- =====================================================================
-- KHULAASAA MALDIVES AGGREGATOR - PRODUCTION SUPABASE / POSTGRESQL SCHEMA
-- =====================================================================
-- This script sets up the full database schema on Supabase PostgreSQL.
-- Atomic domain models, Single Source of Truth for Sources, Entities, Addresses, and People.
-- =====================================================================

-- Extensions
CREATE EXTENSION IF NOT EXISTS "pg_trgm";
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ---------------------------------------------------------------------
-- 1. Canonical Sources Registry (Single Source of Truth for Media & Portals)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    domain TEXT,
    source_type TEXT NOT NULL DEFAULT 'press', -- 'press', 'official', 'wire', 'portal', 'marketplace'
    logo_url TEXT,
    is_active INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_sources_slug ON sources(slug);
CREATE INDEX IF NOT EXISTS idx_sources_type ON sources(source_type);

-- ---------------------------------------------------------------------
-- 2. Canonical Atolls & Islands Directory
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS atolls (
    code TEXT PRIMARY KEY,
    name_en TEXT NOT NULL,
    name_dv TEXT NOT NULL,
    traditional_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS islands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atoll_code TEXT REFERENCES atolls(code) ON DELETE CASCADE,
    name_en TEXT NOT NULL,
    name_dv TEXT,
    is_inhabited INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_islands_atoll ON islands(atoll_code);
CREATE INDEX IF NOT EXISTS idx_islands_name ON islands(name_en);

-- ---------------------------------------------------------------------
-- Reference Tables: Days of the Week (Dhivehi & English)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_days (
    day_number INTEGER PRIMARY KEY, -- 1=Sunday, 2=Monday, ..., 7=Saturday
    code TEXT UNIQUE NOT NULL,       -- 'SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'
    name_en TEXT UNIQUE NOT NULL,   -- 'Sunday', 'Monday', ...
    name_dv TEXT UNIQUE NOT NULL,   -- 'އާދީއްތަ', 'ހޯމަ', ...
    is_weekend INTEGER NOT NULL DEFAULT 0 -- 1 for Friday and Saturday
);

-- ---------------------------------------------------------------------
-- Reference Tables: Gregorian Months (Dhivehi & English)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_months (
    month_number INTEGER PRIMARY KEY, -- 1 to 12
    code TEXT UNIQUE NOT NULL,        -- 'JAN', 'FEB', ...
    name_en TEXT UNIQUE NOT NULL,    -- 'January', 'February', ...
    name_dv TEXT UNIQUE NOT NULL,    -- 'ޖެނުއަރީ', 'ފެބްރުއަރީ', ...
    abbr_en TEXT UNIQUE NOT NULL,    -- 'Jan', 'Feb', ...
    days_count INTEGER NOT NULL      -- 31, 28, 31, 30, ...
);

-- ---------------------------------------------------------------------
-- Reference Tables: Islamic Hijri Months (Dhivehi, English & Arabic)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_hijri_months (
    month_number INTEGER PRIMARY KEY, -- 1 to 12
    name_en TEXT UNIQUE NOT NULL,    -- 'Muharram', 'Safar', ...
    name_dv TEXT UNIQUE NOT NULL,    -- 'މުޙައްރަމް', 'ޞަފަރު', ...
    name_ar TEXT NOT NULL            -- 'محرم', 'صفر', ...
);

-- ---------------------------------------------------------------------
-- Reference Tables: Prayer Times / Janaza Times
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_prayer_times (
    id INTEGER PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,       -- 'fajr', 'dhuhr', 'asr', 'maghrib', 'isha'
    name_en TEXT NOT NULL,           -- 'Fajr', 'Dhuhr', ...
    name_dv TEXT NOT NULL,           -- 'ފަތިސް', 'މެންދުރު', ...
    sort_order INTEGER NOT NULL
);

-- ---------------------------------------------------------------------
-- Reference Tables: Maldivian Districts / Wards
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ref_districts (
    code TEXT PRIMARY KEY,           -- 'H', 'G', 'M', 'MA', 'V', 'H1', 'H2'
    name_en TEXT NOT NULL,           -- 'Henveiru', 'Galolhu', ...
    name_dv TEXT NOT NULL,           -- 'ހެންވޭރު', 'ގަލޮޅު', ...
    island_name_en TEXT NOT NULL DEFAULT 'Male'
);

-- ---------------------------------------------------------------------
-- 3. Canonical Addresses Registry (Single Source of Truth for Maldivian Geography)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code TEXT NOT NULL DEFAULT 'MDV',
    atoll_code TEXT,
    atoll_name_en TEXT,
    atoll_name_dv TEXT,
    island_name_en TEXT,
    island_name_dv TEXT,
    district TEXT,
    road TEXT,
    building_name TEXT,
    floor TEXT,
    unit TEXT,
    postal_code TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    formatted_address TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_addresses_atoll ON addresses(atoll_code, island_name_en);
CREATE INDEX IF NOT EXISTS idx_addresses_formatted ON addresses USING gin (formatted_address gin_trgm_ops);

-- ---------------------------------------------------------------------
-- 3. Canonical People Registry (Single Source of Truth for Individuals)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS people (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nid_number TEXT UNIQUE,
    full_name_en TEXT NOT NULL,
    full_name_dv TEXT,
    gender TEXT,
    phone TEXT,
    email TEXT,
    permanent_address_id BIGINT REFERENCES addresses(id) ON DELETE SET NULL,
    current_address_id BIGINT REFERENCES addresses(id) ON DELETE SET NULL,
    date_of_birth TEXT,
    date_of_death TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_people_nid ON people(nid_number);
CREATE INDEX IF NOT EXISTS idx_people_name_en_trgm ON people USING gin (full_name_en gin_trgm_ops);

-- ---------------------------------------------------------------------
-- 4. Entities Dictionary (Ministries, SOEs, Councils, Companies, Institutions)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS entities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    name_en TEXT NOT NULL,
    name_dv TEXT,
    entity_type TEXT NOT NULL, -- 'SOE', 'Ministry', 'Council', 'Healthcare', 'Education', 'Independent', 'Corporate'
    location TEXT,
    website TEXT,
    registration_number TEXT,
    tin_number TEXT,
    registered_address_id BIGINT REFERENCES addresses(id) ON DELETE SET NULL,
    is_active INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_entities_slug ON entities(slug);
CREATE INDEX IF NOT EXISTS idx_entities_type ON entities(entity_type);
CREATE INDEX IF NOT EXISTS idx_entities_name_en_trgm ON entities USING gin (name_en gin_trgm_ops);

