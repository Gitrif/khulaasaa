-- 13. Enriched Views
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_bids_enriched AS
SELECT
    b.id,
    b.notice_id,
    b.reference_number,
    b.title,
    COALESCE(b.title_en, b.title) AS title_en,
    b.gazette_type,
    b.discipline,
    COALESCE(b.procurement_nature, 'Supply') AS procurement_nature,
    b.published_date,
    b.submission_date,
    b.submission_location,
    b.info_date,
    b.info_location,
    b.source_url,
    b.sources,
    b.document_urls,
    b.is_active,
    s.id AS source_id,
    s.slug AS source_slug,
    s.name AS source_name,
    s.logo_url AS source_logo,
    e.id AS entity_id,
    COALESCE(e.name_en, 'Unknown Agency') AS agency_name_en,
    e.name_dv AS agency_name_dv,
    COALESCE(e.entity_type, 'Other') AS entity_type,
    e.slug AS entity_slug,
    e.location AS entity_location,
    e.website AS entity_website
FROM bids b
LEFT JOIN sources s ON b.source_id = s.id
LEFT JOIN entities e ON b.entity_id = e.id;

CREATE OR REPLACE VIEW v_rentals_enriched AS
SELECT
    r.id,
    r.title,
    r.location,
    r.district,
    r.address,
    r.road,
    r.plot_building,
    r.floor_num,
    r.apartment_unit,
    r.bedrooms,
    r.attached_toilets,
    r.rent_mvr,
    r.deposit_mvr,
    r.furnished,
    r.lift,
    r.available_date,
    r.source_name,
    r.source_url,
    r.image_url,
    r.contact_name,
    r.contact_phone,
    r.is_leased,
    r.is_active,
    s.slug AS source_slug,
    s.logo_url AS source_logo,
    a.atoll_code,
    a.island_name_en,
    a.formatted_address
FROM rentals r
LEFT JOIN sources s ON r.source_id = s.id
LEFT JOIN addresses a ON r.address_id = a.id;

