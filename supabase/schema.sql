-- Extensions
CREATE EXTENSION IF NOT EXISTS "pg_trgm";
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ---------------------------------------------------------------------
-- 1. Entities Dictionary (Ministries, SOEs, Councils, Institutions)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS entities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    name_en TEXT NOT NULL,
    name_dv TEXT,
    entity_type TEXT NOT NULL, -- 'SOE', 'Ministry', 'Council', 'Healthcare', 'Education', 'Independent'
    location TEXT,
    website TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_entities_slug ON entities(slug);
CREATE INDEX IF NOT EXISTS idx_entities_type ON entities(entity_type);
CREATE INDEX IF NOT EXISTS idx_entities_name_en_trgm ON entities USING gin (name_en gin_trgm_ops);

-- ---------------------------------------------------------------------
-- 2. Tenders & Procurement Notices (Gazette & Direct SOE Portals)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id TEXT UNIQUE NOT NULL,
    entity_id BIGINT REFERENCES entities(id) ON DELETE SET NULL,
    reference_number TEXT,
    title TEXT NOT NULL,
    title_en TEXT,
    gazette_type TEXT NOT NULL DEFAULT 'Bid',
    discipline TEXT NOT NULL DEFAULT 'Other',
    procurement_nature TEXT NOT NULL DEFAULT 'Supply', -- 'Service', 'Supply', 'Lease'
    published_date TEXT,
    submission_date TEXT,
    submission_location TEXT,
    info_date TEXT,
    info_location TEXT,
    source_url TEXT NOT NULL,
    sources JSONB DEFAULT '["gazette.gov.mv"]'::jsonb,
    document_urls JSONB DEFAULT '[]'::jsonb,
    raw_details TEXT,
    is_active INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bids_entity_id ON bids(entity_id);
CREATE INDEX IF NOT EXISTS idx_bids_discipline ON bids(discipline);
CREATE INDEX IF NOT EXISTS idx_bids_submission_date ON bids(submission_date);
CREATE INDEX IF NOT EXISTS idx_bids_published_date ON bids(published_date DESC);
CREATE INDEX IF NOT EXISTS idx_bids_is_active ON bids(is_active);
CREATE INDEX IF NOT EXISTS idx_bids_title_trgm ON bids USING gin (title gin_trgm_ops);

-- ---------------------------------------------------------------------
-- 3. Subscribers (Telegram & Viber Channels)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS telegram_subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id TEXT UNIQUE NOT NULL,
    name TEXT,
    disciplines JSONB DEFAULT '[]'::jsonb,
    keywords JSONB DEFAULT '[]'::jsonb,
    is_active INTEGER DEFAULT 1,
    subscribed_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_telegram_subscribers_chat_id ON telegram_subscribers(chat_id);
CREATE INDEX IF NOT EXISTS idx_telegram_subscribers_active ON telegram_subscribers(is_active);

CREATE TABLE IF NOT EXISTS viber_subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viber_user_id TEXT UNIQUE NOT NULL,
    name TEXT,
    avatar TEXT,
    subscribed_categories JSONB DEFAULT '["all"]'::jsonb,
    is_active INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_viber_subscribers_user_id ON viber_subscribers(viber_user_id);
CREATE INDEX IF NOT EXISTS idx_viber_subscribers_active ON viber_subscribers(is_active);

CREATE TABLE IF NOT EXISTS sent_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id TEXT NOT NULL,
    chat_id TEXT NOT NULL,
    sent_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(notice_id, chat_id)
);

CREATE INDEX IF NOT EXISTS idx_sent_alerts_lookup ON sent_alerts(notice_id, chat_id);

-- ---------------------------------------------------------------------
-- 4. News Articles & Aggregated Stories
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS articles (
    id TEXT PRIMARY KEY,
    headline TEXT NOT NULL,
    summary TEXT,
    published_raw TEXT,
    published_iso TEXT,
    minutes_ago INTEGER DEFAULT 60,
    source_key TEXT NOT NULL,
    url TEXT,
    section TEXT DEFAULT 'general',
    topic TEXT DEFAULT 'policy',
    tags JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_articles_published ON articles(published_iso DESC);
CREATE INDEX IF NOT EXISTS idx_articles_source_key ON articles(source_key);
CREATE INDEX IF NOT EXISTS idx_articles_section ON articles(section);
CREATE INDEX IF NOT EXISTS idx_articles_headline_trgm ON articles USING gin (headline gin_trgm_ops);

-- ---------------------------------------------------------------------
-- 5. Sponsored Ads
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sponsored_ads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_name TEXT UNIQUE NOT NULL,
    sponsor_name TEXT NOT NULL,
    text_html TEXT NOT NULL,
    target_category TEXT NOT NULL DEFAULT 'all', -- 'all', 'bids', 'news'
    link_url TEXT,
    is_active INTEGER DEFAULT 1,
    impressions INTEGER DEFAULT 0,
    max_impressions INTEGER DEFAULT NULL,
    expires_at TIMESTAMPTZ DEFAULT NULL,
    pricing_tier TEXT DEFAULT 'custom',
    created_at TIMESTAMPTZ DEFAULT NOW()
