-- ---------------------------------------------------------------------
-- 9. Enriched Bids View
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_bids_enriched AS
SELECT
    b.id,
    b.notice_id,
    b.reference_number,
    b.title,
    COALESCE(b.title_en, b.title) AS title_en,
    b.gazette_type,
    b.discipline,
    COALESCE(b.procurement_nature, 'Supply') AS procurement_nature,
    b.published_date,
    b.submission_date,
    b.submission_location,
    b.info_date,
    b.info_location,
    b.source_url,
    b.sources,
    b.document_urls,
    b.is_active,
    e.id AS entity_id,
    COALESCE(e.name_en, 'Unknown Agency') AS agency_name_en,
    e.name_dv AS agency_name_dv,
    COALESCE(e.entity_type, 'Other') AS entity_type,
    e.slug AS entity_slug,
    e.location AS entity_location,
    e.website AS entity_website
FROM bids b
LEFT JOIN entities e ON b.entity_id = e.id;

-- ---------------------------------------------------------------------
-- 10. Row Level Security (RLS) Policies
-- ---------------------------------------------------------------------
-- Enable RLS across public content tables for client security
ALTER TABLE entities ENABLE ROW LEVEL SECURITY;
ALTER TABLE bids ENABLE ROW LEVEL SECURITY;
ALTER TABLE articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE obituaries ENABLE ROW LEVEL SECURITY;
ALTER TABLE sponsored_ads ENABLE ROW LEVEL SECURITY;

-- Allow anonymous and authenticated read access to public resources
DROP POLICY IF EXISTS "Public read entities" ON entities;
CREATE POLICY "Public read entities" ON entities FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read bids" ON bids;
CREATE POLICY "Public read bids" ON bids FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read articles" ON articles;
CREATE POLICY "Public read articles" ON articles FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read jobs" ON jobs;
CREATE POLICY "Public read jobs" ON jobs FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read obituaries" ON obituaries;
CREATE POLICY "Public read obituaries" ON obituaries FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read sponsored_ads" ON sponsored_ads;
CREATE POLICY "Public read sponsored_ads" ON sponsored_ads FOR SELECT USING (true);

