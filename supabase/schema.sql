CREATE INDEX IF NOT EXISTS idx_sponsored_ads_target ON sponsored_ads(target_category, is_active);

-- ---------------------------------------------------------------------
-- 6. Obituaries & Janaza Notices
-- ---------------------------------------------------------------------
